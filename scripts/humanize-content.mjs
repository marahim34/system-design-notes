async function humanizeMarkdown(content, chNum) {
  let text = content;

  // 1. Stage 1: Priority Replacements
  for (const [regex, replacement] of priorityReplacements) {
    text = text.replace(regex, replacement);
  }

  // 2. Stage 2: General Dictionary Replacements
  for (const [regex, replacement] of generalReplacements) {
    text = text.replace(regex, replacement);
  }

  // 3. Stage 3: Apply custom human intro & title if available
  const override = chapterHumanOverrides[chNum];
  if (override) {
    // Replace H1 title
    text = text.replace(/^#\s+.*$/m, `# ${override.title}`);

    // Replace Introduction section
    const introPattern = /(##\s+ভূমিকা[^\n]*\n)([\s\S]*?)(?=\n---\n|\n##\s+)/;
    if (introPattern.test(text)) {
      text = text.replace(introPattern, `$1${override.intro}\n\n`);
    } else {
      // If no intro heading matched, check if H1 has an intro before the first ---
      const topIntroPattern = /(#\s+[^\n]+\n+)([\s\S]*?)(?=\n---\n|\n##\s+)/;
      if (topIntroPattern.test(text)) {
        text = text.replace(topIntroPattern, `$1## ভূমিকা\n${override.intro}\n\n`);
      }
    }
  }

  return text;
}

async function processAll() {
  console.log('✨ Starting Human-Tone Polish across all 28 chapters...\n');
  const entries = fs.readdirSync(rootDir, { withFileTypes: true });
  const chapterDirs = entries
    .filter(e => e.isDirectory() && /^\d+\./.test(e.name))
    .sort((a, b) => {
      const numA = parseInt(a.name.match(/^(\d+)/)[1], 10);
      const numB = parseInt(b.name.match(/^(\d+)/)[1], 10);
      return numA - numB;
    });

  let modifiedCount = 0;
  for (const dir of chapterDirs) {
    const num = parseInt(dir.name.match(/^(\d+)/)[1], 10);
    const chapterPath = path.join(rootDir, dir.name);
    const bnFile = path.join(chapterPath, 'Readme.bn.md');

    if (fs.existsSync(bnFile)) {
      const raw = fs.readFileSync(bnFile, 'utf8');
      const polished = await humanizeMarkdown(raw, num);
      fs.writeFileSync(bnFile, polished, 'utf8');
      console.log(`  ✓ Polished Chapter ${String(num).padStart(2, '0')}: ${dir.name}`);
      modifiedCount++;
    } else {
      console.warn(`  ⚠️ Missing Readme.bn.md in ${dir.name}`);
    }
  }

  console.log(`\n🎉 All ${modifiedCount} chapters successfully converted to natural, human tech-mentor Bengali!`);
}

processAll().catch(err => {
  console.error('Error humanizing content:', err);
  process.exit(1);
});
